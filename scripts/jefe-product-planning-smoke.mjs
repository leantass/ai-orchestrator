import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { createProductPlanning, evolveProductPlanning, migrateLegacyPlanning, validateProductPlanning, validateGeneratedArtifact } from '../electron/jefe-product-planning.cjs'
import { createFirstVersionFromRun } from '../electron/jefe-project-creation.cjs'
import { createProjectPersistence } from '../electron/jefe-project-persistence.cjs'
import { createProjectLifecycle } from '../electron/jefe-project-lifecycle.cjs'

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'jefe-product-planning-'))
const briefA = createProductPlanning({ projectName: 'Casa Lumen', brief: 'Crear una landing premium para un estudio de arquitectura que busca captar consultas de personas que quieren construir o remodelar su casa.', objective: 'Captar consultas de construcción y remodelación.', businessType: 'estudio de arquitectura', audience: 'personas que quieren construir o remodelar su casa', problem: 'Las personas necesitan confiar antes de pedir una consulta.', proposition: 'Arquitectura clara, sensible y preparada para el próximo paso.', visualDirection: 'comercial', primaryCta: 'Solicitar una consulta', colors: ['#123456'] })
const briefB = createProductPlanning({ projectName: 'Ritmo Local', brief: 'Crear un sitio editorial para músicos independientes que necesitan presentar su obra y fechas.', objective: 'Presentar obra y fechas.', businessType: 'colectivo musical', audience: 'personas que descubren música independiente', proposition: 'Una escena viva, cercana y con criterio.', visualDirection: 'editorial' })
assert.notEqual(briefA.brief.briefId, briefB.brief.briefId)
assert.notEqual(briefA.content.title, briefB.content.title)
assert.notEqual(briefA.experience.sections.join('|'), briefB.experience.sections.join('|'))
const changed = evolveProductPlanning(briefA, 'Cambiar la estructura y sumar una sección de preguntas frecuentes.', { projectName: 'Casa Lumen', audience: briefA.brief.audience, proposition: briefA.brief.valueProposition, businessType: 'estudio de arquitectura', visualDirection: 'comercial' })
assert.equal(changed.revision, 1)
assert.equal(changed.changeHistory[0].routedTo, 'ExperiencePlan')
assert.equal(changed.changeHistory[0].classification, 'content')
assert.deepEqual(changed.changeHistory[0].routedPlans, ['ExperiencePlan', 'ContentPlan', 'BuildPlan'])
assert.equal(changed.brief.briefId, briefA.brief.briefId)
assert.equal(changed.content.briefId, changed.brief.briefId)
assert.equal(changed.strategy.briefId, changed.brief.briefId)
assert.doesNotThrow(() => validateProductPlanning(changed))
assert.deepEqual(changed.brief, briefA.brief)
assert.ok(changed.experience.sections.includes('faq'))
assert.ok(changed.content.faq.length > 0)
assert.ok(changed.content.trust.length > 0)
const legacy = JSON.parse(JSON.stringify(briefA))
legacy.brief.valueProposition = 'Arquitectura clara, sensible y preparada para el pr?ximo paso.'
legacy.content.briefId = 'brief-legacy-drift'
const migrated = migrateLegacyPlanning(legacy)
assert.equal(migrated.brief.briefId, briefA.brief.briefId)
assert.equal(migrated.content.briefId, briefA.brief.briefId)
assert.equal(migrated.strategy.briefId, briefA.brief.briefId)
assert.equal(migrated.brief.valueProposition, 'Arquitectura clara, sensible y preparada para el próximo paso.')
const first = await createFirstVersionFromRun({ destinationRoot: root, allowedRoots: [root], projectId: 'planning-smoke', runId: 'planning-run', versionId: 'planning-version', projectType: 'agency_site', platform: 'web', generationProfile: 'commercial_site', creativeDirection: 'comercial', projectName: 'Casa Lumen', brief: 'Crear una landing para captar consultas de arquitectura.', businessType: 'estudio de arquitectura', audience: 'familias que remodelan su casa', proposition: 'Diseño claro para decisiones importantes.', primaryCta: 'Solicitar una consulta', brandSpec: { name: 'Casa Lumen', primaryColor: '#123456' } })
if (!first.ok) throw new Error(JSON.stringify(first.error))
const manifest = JSON.parse(await fs.readFile(first.artifacts.manifestPath, 'utf8'))
const generatedPlanning = JSON.parse(await fs.readFile(path.join(first.artifacts.projectRoot, 'data', 'planning.json'), 'utf8'))
assert.ok(manifest.contract.planning.brief)
assert.ok(manifest.contract.planning.strategy)
assert.ok(manifest.contract.planning.experience)
assert.ok(manifest.contract.planning.visual)
assert.ok(manifest.contract.planning.content)
assert.ok(manifest.contract.planning.build)
assert.deepEqual(manifest.contract.planning, generatedPlanning)
assert.equal(generatedPlanning.content.briefId, generatedPlanning.brief.briefId)
assert.doesNotThrow(() => validateProductPlanning(generatedPlanning))
const html = await fs.readFile(path.join(first.artifacts.projectRoot, 'app', 'index.html'), 'utf8')
const css = await fs.readFile(path.join(first.artifacts.projectRoot, 'app', 'styles.css'), 'utf8')
const js = await fs.readFile(path.join(first.artifacts.projectRoot, 'app', 'app.js'), 'utf8')
assert.match(html, /familias que remodelan su casa/u)
assert.match(html, /Solicitar una consulta/u)
assert.match(html, /conversion/u)
assert.ok(first.artifacts.artifactPaths.includes('data/planning.json'))
assert.doesNotThrow(() => validateGeneratedArtifact(generatedPlanning, { html, css, js }))
const persistence = createProjectPersistence({ root })
await persistence.registerManifest(first.artifacts.manifestPath)
const lifecycle = createProjectLifecycle({ root, persistence })
const changedVersion = await lifecycle.createVersion({ projectId: 'planning-smoke', changeRequest: 'Cambiar el contenido de beneficios para enfatizar confianza y sumar una pregunta frecuente.' })
assert.equal(changedVersion.ok, true)
const changedManifest = JSON.parse(await fs.readFile(path.join(root, 'planning-smoke', changedVersion.versionId, 'manifest.json'), 'utf8'))
assert.equal(changedManifest.contract.planning.revision, 1)
assert.equal(changedManifest.contract.planning.changeHistory[0].routedTo, 'ExperiencePlan')
const compared = await lifecycle.compare('planning-smoke', 'planning-version', changedVersion.versionId)
assert.ok(compared.artifacts.modified.length > 0)
const restored = await lifecycle.restore('planning-smoke', 'planning-version')
assert.equal(restored.ok, true)
assert.equal(restored.project.changeOrigin.reference, 'restore-planning-version')
assert.throws(() => createProductPlanning({ brief: 'Crear una landing para el pr?ximo paso.' }), (error) => error.code === 'INVALID_UTF8_TEXT')
await fs.rm(root, { recursive: true, force: true })
console.log(JSON.stringify({ ok: true, checks: 38, briefA: briefA.brief.briefId, briefB: briefB.brief.briefId, changedRevision: changed.revision, generated: first.artifacts.artifactPaths }, null, 2))
